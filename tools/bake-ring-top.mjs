// Bake the tops of the fire ring's stones and the hearth stones into polar height tables, so the
// star fire's logs (src/world/camp/star.js) can rest on the stones and never pass through one.
// Each table is the highest point of the model's surface in each cell of angle by radius, in the
// ring model's own frame (angle 0 along +x, toward +z at 90 degrees), in millimeters. Writes
// src/world/camp/ring-top.js. Run again whenever fire-ring.glb or hearth-stones.glb changes:
//
//   node tools/bake-ring-top.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { packModel } from '../src/render/passes/props.js';

const root = resolve(dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const ANGLES = 90, DR = 0.02;

/** @param {string} file @param {number} maxR */
function bake(file, maxR) {
  const b = readFileSync(resolve(root, 'assets/models/camp', file));
  const p = packModel(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
  const radii = Math.ceil(maxR / DR), top = new Float32Array(ANGLES * radii);
  const V = (/** @type {number} */ i) => [p.data[i * 11], p.data[i * 11 + 1], p.data[i * 11 + 2]];
  /** @param {number} x @param {number} y @param {number} z */
  const mark = (x, y, z) => {
    const ri = Math.floor(Math.hypot(x, z) / DR);
    if (ri >= radii) return;
    const ai = ((Math.floor(((Math.atan2(z, x) / (2 * Math.PI)) * ANGLES)) % ANGLES) + ANGLES) % ANGLES;
    top[ai * radii + ri] = Math.max(top[ai * radii + ri], y);
  };
  // Every triangle sampled about every 4 mm, so no cell between its corners is missed.
  for (let t = 0; t < p.indices.length; t += 3) {
    const a = V(p.indices[t]), b2 = V(p.indices[t + 1]), c = V(p.indices[t + 2]);
    const edge = Math.max(Math.hypot(a[0] - b2[0], a[2] - b2[2]), Math.hypot(a[0] - c[0], a[2] - c[2]), Math.hypot(b2[0] - c[0], b2[2] - c[2]));
    const n = Math.max(1, Math.ceil(edge / 0.004));
    for (let i = 0; i <= n; i++) for (let j = 0; j <= n - i; j++) {
      const u = i / n, v = j / n, w = 1 - u - v;
      mark(a[0] * w + b2[0] * u + c[0] * v, a[1] * w + b2[1] * u + c[1] * v, a[2] * w + b2[2] * u + c[2] * v);
    }
  }
  return { radii, mm: [...top].map((y) => Math.round(y * 1000)) };
}

const ring = bake('fire-ring.glb', 0.52), hearth = bake('hearth-stones.glb', 0.22);
/** @param {{ radii: number, mm: number[] }} t */
const rows = (t) => Array.from({ length: ANGLES }, (_, a) => '    ' + t.mm.slice(a * t.radii, (a + 1) * t.radii).join(',')).join(',\n');
writeFileSync(resolve(root, 'src/world/camp/ring-top.js'), `// @ts-check
// Generated by tools/bake-ring-top.mjs from fire-ring.glb and hearth-stones.glb; do not edit.
// The highest point of each model's surface in each cell of angle (${ANGLES} cells round, the first
// from angle 0 along the model's +x toward +z) by radius (cells ${DR} m wide from the middle), in mm.

export const ANGLES = ${ANGLES};
export const DR = ${DR};

/** The fire ring's stones (and its ash bed). */
export const RING = { radii: ${ring.radii}, mm: [
${rows(ring)},
] };

/** The hearth stones, set in the ring's middle in the same frame. */
export const HEARTH = { radii: ${hearth.radii}, mm: [
${rows(hearth)},
] };
`);
console.log('ring', ring.radii, 'radii; hearth', hearth.radii, 'radii');
